# ============ CELLULE 5 : sections 5 et 6, algorithme et protocole ============
from sklearn.base import clone
from sklearn.model_selection import StratifiedKFold
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import confusion_matrix, roc_auc_score, balanced_accuracy_score

md("""
## 5. Algorithme : régression logistique (n° 8)
**Choix.** Elle fournit directement une probabilité P(mauvais), nécessaire pour fixer un seuil à coûts asymétriques ; elle est interprétable et adaptée à 800 dossiers d'apprentissage. **Alternative non retenue :** le Gradient Boosting (n° 14), plus flexible mais plus exposé au surapprentissage sur si peu de données et moins lisible.

**Principe.** Le modèle calcule un score linéaire z = w·x + b puis P(mauvais | x) = 1 / (1 + e^(−z)). Ici x est le vecteur des variables préparées, w les coefficients appris et b l'ordonnée à l'origine. L'apprentissage minimise la perte logarithmique avec pénalité L2 : Σ −[y·ln p + (1−y)·ln(1−p)] + (1/(2C))·‖w‖². **Paramètres appris :** w et b. **Hyperparamètres :** C, l'inverse de la régularisation (C petit = coefficients très contraints, risque de sous-apprentissage ; C grand = peu de contrainte, risque de surapprentissage), et le seuil s de refus (on refuse si P(mauvais) ≥ s).

## 6. Protocole expérimental
Découpage 80/20 stratifié (graine 42). Référence naïve : « tout refuser ». Réglage de C et du seuil par validation croisée stratifiée à 5 plis **sur l'apprentissage seulement**. Métrique principale : coût moyen par dossier. Métriques secondaires : AUC et exactitude équilibrée, robustes au déséquilibre. Le test n'est utilisé qu'une fois, à la fin.
""")

def cout_moyen(y_vrai, y_pred):
    """y = 1 : mauvais crédit ; prédire 1 = refuser, prédire 0 = accepter."""
    y_vrai, y_pred = np.asarray(y_vrai), np.asarray(y_pred)
    faux_bons = ((y_vrai == 1) & (y_pred == 0)).sum()
    faux_mauvais = ((y_vrai == 0) & (y_pred == 1)).sum()
    return (COUT_FAUX_BON * faux_bons + COUT_FAUX_MAUVAIS * faux_mauvais) / len(y_vrai)

ref_refuser = cout_moyen(y_train, np.ones(len(y_train)))
ref_accepter = cout_moyen(y_train, np.zeros(len(y_train)))
print(f"Référence 'tout refuser' : {ref_refuser:.3f} | 'tout accepter' : {ref_accepter:.3f} (apprentissage)")
SEUIL_REUSSITE = 0.85 * 0.70
print(f"Seuil de réussite fixé : coût test <= {SEUIL_REUSSITE:.3f} (15 % sous 0,70)")

VALEURS_C = [0.01, 0.03, 0.1, 0.3, 1.0]
SEUILS = np.round(np.arange(0.05, 0.81, 0.01), 2)
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=GRAINE)
Xtr = X_train.reset_index(drop=True); ytr = y_train.reset_index(drop=True)

def modele(C):
    return Pipeline([("prep", clone(preparation)),
                     ("clf", LogisticRegression(C=C, max_iter=2000, random_state=GRAINE))])

def proba_validation(C, Xa, ya):
    oof = np.zeros(len(ya)); plis = []
    for i_tr, i_va in cv.split(Xa, ya):
        m = modele(C).fit(Xa.iloc[i_tr], ya.iloc[i_tr])
        oof[i_va] = m.predict_proba(Xa.iloc[i_va])[:, 1]
        plis.append((i_tr, i_va, m.predict_proba(Xa.iloc[i_tr])[:, 1]))
    return oof, plis

def meilleur_seuil(proba, ya):
    couts = [cout_moyen(ya, proba >= s) for s in SEUILS]
    return SEUILS[int(np.argmin(couts))], min(couts)

resultats = []
for C in VALEURS_C:
    oof, plis = proba_validation(C, Xtr, ytr)
    s, c_val = meilleur_seuil(oof, ytr)
    c_plis = [cout_moyen(ytr.iloc[i_va], oof[i_va] >= s) for _, i_va, _ in plis]
